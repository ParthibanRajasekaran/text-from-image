#!/usr/bin/env node
/**
 * Vendor the OCR engine files into public/ocr/ so the site serves them itself.
 *
 *   npm run vendor:ocr          copy files from node_modules and write the manifest
 *   npm run vendor:ocr -- --check   verify public/ocr matches node_modules (for CI)
 *
 * Sources (all pinned by package-lock.json):
 *   tesseract.js            dist/worker.min.js                 the worker script
 *   tesseract.js-core       tesseract-core-simd-lstm.wasm.js   the engine, SIMD build
 *                           tesseract-core-lstm.wasm.js        the engine, fallback build
 *   @tesseract.js-data/eng  4.0.0_best_int/eng.traineddata.gz  English language data
 *
 * Why `.wasm.js` and not `.wasm`: tesseract.js 5.1.1 loads `<corePath>/tesseract-core-*.wasm.js`
 * with importScripts. Those files already contain the WebAssembly, so no separate .wasm file
 * is requested.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public', 'ocr');
const check = process.argv.includes('--check');

const pkgVersion = (name) =>
  JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8')).version;

const files = [
  ['tesseract.js/dist/worker.min.js', 'worker.min.js'],
  ['tesseract.js/dist/worker.min.js.LICENSE.txt', 'worker.min.js.LICENSE.txt'],
  ['tesseract.js-core/tesseract-core-simd-lstm.wasm.js', 'tesseract-core-simd-lstm.wasm.js'],
  ['tesseract.js-core/tesseract-core-lstm.wasm.js', 'tesseract-core-lstm.wasm.js'],
  ['@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz', 'eng.traineddata.gz'],
];

const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

const manifest = {
  note: 'Generated by scripts/vendor-ocr-assets.mjs. Do not edit by hand.',
  packages: {
    'tesseract.js': pkgVersion('tesseract.js'),
    'tesseract.js-core': pkgVersion('tesseract.js-core'),
    '@tesseract.js-data/eng': pkgVersion('@tesseract.js-data/eng'),
  },
  licences: {
    'tesseract.js': 'Apache-2.0',
    'tesseract.js-core': 'Apache-2.0',
    '@tesseract.js-data/eng': 'MIT (package); the traineddata files come from the Tesseract project, Apache-2.0',
  },
  files: {},
};

let failed = false;
if (!check) mkdirSync(out, { recursive: true });

for (const [from, name] of files) {
  const src = join(root, 'node_modules', from);
  const dest = join(out, name);
  if (!existsSync(src)) {
    console.error(`missing source: node_modules/${from} (run npm ci)`);
    process.exit(1);
  }
  if (!check) copyFileSync(src, dest);
  if (!existsSync(dest)) {
    console.error(`missing vendored file: public/ocr/${name}`);
    failed = true;
    continue;
  }
  const digest = sha256(dest);
  if (check && digest !== sha256(src)) {
    console.error(`out of date: public/ocr/${name} differs from node_modules/${from}`);
    failed = true;
  }
  manifest.files[name] = { bytes: statSync(dest).size, sha256: digest };
}

if (check) {
  const manifestPath = join(out, 'manifest.json');
  if (!existsSync(manifestPath)) {
    console.error('missing public/ocr/manifest.json');
    failed = true;
  } else {
    const onDisk = JSON.parse(readFileSync(manifestPath, 'utf8'));
    if (JSON.stringify(onDisk.files) !== JSON.stringify(manifest.files)) {
      console.error('public/ocr/manifest.json does not match the files on disk');
      failed = true;
    }
  }
  if (failed) process.exit(1);
  console.log('public/ocr is in sync with node_modules');
} else {
  writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  console.log(`vendored ${files.length} files into public/ocr`);
}
