// RenderCheck benchmark runner. Usage: npm run bench   (builds dist first, see package.json)
// Env: RENDERCHECK_BENCH_CHROMIUM=/path/to/chrome  to use a specific Chromium binary.
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium, expect } from '@playwright/test';
import { verifyText, shutdown } from '../dist/core/index.mjs';
import { fixtures, bannerHtml } from './fixtures.mjs';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, 'out');
mkdirSync(outDir, { recursive: true });

const MIN_CONTRAST = 4.5;
const VIEWPORT = { width: 520, height: 120 };

const browser = await chromium.launch({ executablePath: process.env.RENDERCHECK_BENCH_CHROMIUM || undefined });
const context = await browser.newContext({ viewport: VIEWPORT, deviceScaleFactor: 1, colorScheme: 'light' });
const page = await context.newPage();

// Render the two banner images (text baked into pixels).
async function banner(text) {
  await page.setContent(bannerHtml(text));
  const png = await page.screenshot({ clip: { x: 0, y: 0, width: 360, height: 40 } });
  return `data:image/png;base64,${png.toString('base64')}`;
}
const ctx = { images: { bannerStale: await banner('Free delivery over $30'), bannerOk: await banner('Free delivery over $50') } };

// Warm-up so one-off OCR worker start-up is not charged to the first fixture.
await page.setContent(fixtures.find((f) => f.id === 'control-black-on-white').html);
await verifyText({ image: new Uint8Array(await page.screenshot()), expected: 'Order confirmed' });

const classify = (truth, flagged) => (truth === 'bug' ? (flagged ? 'TP' : 'FN') : flagged ? 'FP' : 'TN');

const rows = [];
for (const f of fixtures) {
  await page.setContent(typeof f.html === 'function' ? f.html(ctx) : f.html);

  // (a) naive DOM assertion: element exists and its text contains the expected string.
  let naiveFlagged = false;
  try {
    await expect(page.locator('#target')).toContainText(f.expected, { timeout: 1000 });
  } catch {
    naiveFlagged = true;
  }

  // (b) RenderCheck on the screenshot. No DOM text is passed, so only pixels are judged.
  const shot = await page.screenshot({ path: path.join(outDir, `${f.id}.png`) });
  const report = await verifyText({
    image: new Uint8Array(shot),
    expected: f.expected,
    options: { minContrastRatio: MIN_CONTRAST },
  });
  const rcFlagged = !report.pass;

  rows.push({
    id: f.id,
    class: f.cls,
    truth: f.truth,
    expected: f.expected,
    why: f.why,
    naive: { flagged: naiveFlagged, outcome: classify(f.truth, naiveFlagged) },
    rendercheck: {
      flagged: rcFlagged,
      outcome: classify(f.truth, rcFlagged),
      failure: report.failure ?? null,
      read: report.read,
      confidence: report.confidence,
      minContrast: report.minContrast === undefined ? null : Math.round(report.minContrast * 100) / 100,
    },
    ocrMs: Math.round(report.ocr.metrics.durationMs),
  });
}

const count = (key) => {
  const c = { TP: 0, FN: 0, FP: 0, TN: 0 };
  for (const r of rows) c[r[key].outcome]++;
  return c;
};
const summary = { fixtures: rows.length, bugs: rows.filter((r) => r.truth === 'bug').length, controls: rows.filter((r) => r.truth === 'ok').length, naive: count('naive'), rendercheck: count('rendercheck') };
const matrix = rows.map((r) => `${r.id}: naive=${r.naive.outcome} rendercheck=${r.rendercheck.outcome} (${r.rendercheck.failure ?? 'pass'})`);

const environment = {
  node: process.version,
  platform: `${os.platform()} ${os.arch()}`,
  playwright: require('@playwright/test/package.json').version,
  chromium: browser.version(),
  tesseractJs: require('tesseract.js/package.json').version,
  rendercheck: require('../package.json').version,
  viewport: `${VIEWPORT.width}x${VIEWPORT.height} @1x`,
  minContrastRatio: MIN_CONTRAST,
};
await browser.close();
await shutdown();

const results = { environment, summary, matrix, rows };
writeFileSync(path.join(here, 'results.json'), JSON.stringify(results, null, 2) + '\n');

// ---- results.md ----
// Escape backslashes first so an existing backslash cannot undo the pipe escape.
const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
const cell = (s) => '`' + esc(s || '(nothing)') + '`';
const sum = (k) => {
  const c = summary[k];
  return `| ${k === 'naive' ? 'Naive DOM assertion (toContainText)' : 'RenderCheck verifyText, minContrastRatio 4.5'} | ${c.TP} | ${c.FN} | ${c.FP} | ${c.TN} |`;
};
const md = [
  '# RenderCheck benchmark results',
  '',
  'Generated by `npm run bench`. Self-made suite by the project author: it shows the class of bug, it is not a claim of general accuracy. See README.md.',
  '',
  '## Environment',
  '',
  ...Object.entries(environment).map(([k, v]) => `- ${k}: ${v}`),
  '',
  `## Summary (${summary.fixtures} fixtures: ${summary.bugs} with a bug, ${summary.controls} where a person can read the text)`,
  '',
  'A detector "flags" a fixture when its assertion fails. TP = bug flagged, FN = bug missed, FP = readable text flagged, TN = readable text passed.',
  '',
  '| Detector | TP | FN | FP | TN |',
  '| --- | --- | --- | --- | --- |',
  sum('naive'),
  sum('rendercheck'),
  '',
  '## Per fixture',
  '',
  'OCR ms is the time of the OCR step for that screenshot on the machine above, after one warm-up run. It varies between runs; the outcome columns do not.',
  '',
  '| Fixture | Class | Truth | Naive | RenderCheck | RC failure | OCR read | Min contrast | OCR ms |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| ${r.id} | ${r.class} | ${r.truth} | ${r.naive.outcome} | ${r.rendercheck.outcome} | ${r.rendercheck.failure ?? 'none'} | ${cell(r.rendercheck.read.slice(0, 60))} | ${r.rendercheck.minContrast ?? 'n/a'} | ${r.ocrMs} |`
  ),
  '',
  '## Fixture notes',
  '',
  ...rows.map((r) => `- **${r.id}** (expects "${r.expected}"): ${r.why}`),
  '',
].join('\n');
writeFileSync(path.join(here, 'results.md'), md);

console.log(matrix.join('\n'));
console.log('\n' + JSON.stringify(summary));
